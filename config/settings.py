VERCEL_DOMAIN_VARIABLES = (
    "VERCEL_URL",
    "VERCEL_BRANCH_URL",
    "VERCEL_PROJECT_PRODUCTION_URL",
)

VERCEL_DOMAINS = []

for variable in VERCEL_DOMAIN_VARIABLES:
    domain = os.environ.get(variable, "").strip()

    if domain:
        domain = domain.removeprefix("https://")
        domain = domain.removeprefix("http://")
        domain = domain.split("/")[0]

        if domain:
            VERCEL_DOMAINS.append(domain)

ALLOWED_HOSTS = list(dict.fromkeys(ALLOWED_HOSTS + VERCEL_DOMAINS))

# Explicitly configured HTTPS origins, including custom domains.
CSRF_TRUSTED_ORIGINS = env.list(
    "DJANGO_CSRF_TRUSTED_ORIGINS",
    default=[],
)

for domain in VERCEL_DOMAINS:
    origin = f"https://{domain}"

    if origin not in CSRF_TRUSTED_ORIGINS:
        CSRF_TRUSTED_ORIGINS.append(origin)


